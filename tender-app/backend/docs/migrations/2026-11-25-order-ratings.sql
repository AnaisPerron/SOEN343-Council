-- RVW (R-RVW-01): one customer rating per delivered order.
-- Restaurant and courier ids are copied from the order when the rating is stored.
BEGIN;

CREATE TABLE IF NOT EXISTS order_ratings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    customer_id BIGINT NOT NULL REFERENCES users(id),
    restaurant_id BIGINT NOT NULL REFERENCES restaurants(id),
    courier_id BIGINT REFERENCES courier_profiles(user_id) ON DELETE SET NULL,
    restaurant_stars INTEGER NOT NULL,
    courier_stars INTEGER,
    comment VARCHAR(500),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_order_ratings_order UNIQUE (order_id),
    CONSTRAINT chk_order_ratings_restaurant_stars CHECK (restaurant_stars BETWEEN 1 AND 5),
    CONSTRAINT chk_order_ratings_courier_stars CHECK (courier_stars IS NULL OR courier_stars BETWEEN 1 AND 5)
);
CREATE INDEX IF NOT EXISTS idx_order_ratings_restaurant ON order_ratings (restaurant_id);
CREATE INDEX IF NOT EXISTS idx_order_ratings_courier ON order_ratings (courier_id);
ALTER TABLE order_ratings ENABLE ROW LEVEL SECURITY;

COMMIT;
